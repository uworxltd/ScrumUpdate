package uk.co.uworx.khoji.agile.internal.model;

public class CustomFieldTemplateParameters
{
  String spec = "";
  String teamBoardCfValue = "";
  String storyPointsCfValue = "";
  String epicIdCfValue = "";
  String sprintListCfValue = "";
  String highLevelEstimateCfValue = "";

  public String getSpec()
  {
    return spec;
  }

  public void setSpec(final String spec)
  {
    this.spec = spec;
  }

  public String getTeamBoardCfValue()
  {
    return teamBoardCfValue;
  }

  public void setTeamBoardCfValue(final String teamBoardCfValue)
  {
    this.teamBoardCfValue = teamBoardCfValue;
  }

  public String getStoryPointsCfValue()
  {
    return storyPointsCfValue;
  }

  public void setStoryPointsCfValue(final String storyPointsCfValue)
  {
    this.storyPointsCfValue = storyPointsCfValue;
  }

  public String getEpicIdCfValue()
  {
    return epicIdCfValue;
  }

  public void setEpicIdCfValue(final String epicIdCfValue)
  {
    this.epicIdCfValue = epicIdCfValue;
  }

  public String getSprintListCfValue()
  {
    return sprintListCfValue;
  }

  public void setSprintListCfValue(final String sprintListCfValue)
  {
    this.sprintListCfValue = sprintListCfValue;
  }

  public String getHighLevelEstimateCfValue()
  {
    return highLevelEstimateCfValue;
  }

  public void setHighLevelEstimateCfValue(final String highLevelEstimateCfValue)
  {
    this.highLevelEstimateCfValue = highLevelEstimateCfValue;
  }
}
